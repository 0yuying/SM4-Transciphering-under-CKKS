// CombineBin
func CombineBin(var1, var2 []*BitSet) []*BitSet {
	var result []*BitSet
	for _, v1 := range var1 {
		for _, v2 := range var2 {
			result = append(result, Xor(v1, v2))
		}
	}
	return result
}

// LayeredCombineBin
func LayeredCombineBin(variables []*BitSet) ([]*BitSet, error) {
	if len(variables)%2 != 0 {
		return nil, errors.New("the input must be even")
	}

	if len(variables) == 2 {
		result := []*BitSet{variables[0], variables[1], Xor(variables[0], variables[1])}
		return result, nil
	}

	mid := len(variables) / 2
	left, err := LayeredCombineBin(variables[:mid])
	if err != nil {
		return nil, err
	}
	right, err := LayeredCombineBin(variables[mid:])
	if err != nil {
		return nil, err
	}

	combined := CombineBin(left, right)
	result := append(combined, left...)
	result = append(result, right...)

	return result, nil
}

// Combine
func Combine(eval *bootstrapping.Evaluator, var1, var2 []*rlwe.Ciphertext) []*rlwe.Ciphertext {
	result := make([]*rlwe.Ciphertext, 0, len(var1)*len(var2))
	for i := 0; i < len(var1); i++ {
		for j := 0; j < len(var2); j++ {
			tmp, err := eval.MulRelinNew(var1[i], var2[j])
			if err != nil {
				panic(err)
			}
			eval.Rescale(tmp, tmp)
			result = append(result, tmp)
		}
	}
	return result
}

// LayeredCombine
func LayeredCombine(eval *bootstrapping.Evaluator, variables []*rlwe.Ciphertext) ([]*rlwe.Ciphertext, error) {
	if len(variables) == 0 || len(variables)%2 != 0 {
		return nil, errors.New("the input must be even")
	}

	// Build base groups for each variable pair:
	// [x0, x1, x0*x1], [x2, x3, x2*x3], ...
	groups := make([][]*rlwe.Ciphertext, 0, len(variables)/2)
	for i := 0; i < len(variables); i += 2 {
		tmp, err := eval.MulRelinNew(variables[i], variables[i+1])
		if err != nil {
			panic(err)
		}
		eval.Rescale(tmp, tmp)
		base := make([]*rlwe.Ciphertext, 3)
		base[0] = variables[i]
		base[1] = variables[i+1]
		base[2] = tmp
		groups = append(groups, base)
	}

	if len(groups) == 1 {
		return groups[0], nil
	}

	for len(groups) > 1 {
		if len(groups)%2 != 0 {
			return nil, errors.New("the input must be power-of-two sized")
		}
		next := make([][]*rlwe.Ciphertext, 0, len(groups)/2)
		for i := 0; i < len(groups); i += 2 {
			left := groups[i]
			right := groups[i+1]
			combined := Combine(eval, left, right)
			merged := make([]*rlwe.Ciphertext, 0, len(combined)+len(left)+len(right))
			merged = append(merged, combined...)
			merged = append(merged, left...)
			merged = append(merged, right...)
			next = append(next, merged)
		}
		groups = next
	}
	return groups[0], nil
}

